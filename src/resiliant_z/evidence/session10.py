class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


def _canonical_bytes(value: object) -> bytes:
    if isinstance(value, BaseModel):
        value = value.model_dump(mode="json")
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _sha256_value(value: object) -> str:
    return _sha256_bytes(_canonical_bytes(value))


class Session10Config(StrictModel):
    """Trusted, predeclared analysis bounds; not generated by a hypothesis provider."""

    schema_version: SchemaVersion = "1.0.0"
    config_id: str = Field(
        min_length=1, max_length=128, pattern=r"^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$"
    )
    primary_split: Literal["validation"] = "validation"
    expected_metric_unit: str = Field(min_length=1, max_length=128)
    metric_min_value: float = Field(allow_inf_nan=False)
    metric_max_value: float = Field(allow_inf_nan=False)
    minimum_pairs: int = Field(default=3, ge=2, le=25)
    minimum_practical_effect: float = Field(default=0.0, ge=0.0, allow_inf_nan=False)
    confidence_level: Literal[0.95] = 0.95
    max_plan_bytes: int = Field(default=1_048_576, ge=1_024, le=8_388_608)
    max_receipt_bytes: int = Field(default=16_777_216, ge=1_024, le=268_435_456)
    max_result_bytes: int = Field(default=1_048_576, ge=256, le=16_777_216)
    max_runs: int = Field(default=200, ge=2, le=200)
    max_receipts: int = Field(default=200, ge=1, le=200)

    @model_validator(mode="after")
    def validate_bounds(self) -> Session10Config:
        if self.metric_min_value >= self.metric_max_value:
            raise ValueError("metric_min_value must be strictly less than metric_max_value")
        if not self.expected_metric_unit.strip():
            raise ValueError("expected_metric_unit must not be blank")
        return self


class MetricObservation(StrictModel):
    value: float | None = Field(default=None, allow_inf_nan=False)
    unit: str = Field(min_length=1, max_length=128)
    quality: MetricQuality
    reason: str | None = Field(default=None, max_length=512)

    @model_validator(mode="after")
    def validate_quality_value(self) -> MetricObservation:
        if self.quality == "measured":
            if self.value is None:
                raise ValueError(
                    "quality='measured' requires a numeric value; measured zero is valid"
                )
        else:
            if self.value is not None:
                raise ValueError(
                    "unmeasured metric values must be null; do not encode them as zero"
                )
            if not self.reason or not self.reason.strip():
                raise ValueError("unmeasured metrics require a reason")
        return self


class RunResultArtifact(StrictModel):
    """Normalized JSON result payload, stored separately and hashed by its receipt."""

    schema_version: SchemaVersion = "1.0.0"
    run_id: str = Field(pattern=r"^run-[0-9a-f]{24}$")
    plan_id: str = Field(pattern=r"^plan-[0-9a-f]{24}$")
    request_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    scenario_id: str = Field(min_length=1, max_length=128)
    scenario_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    backend_id: Literal["discrete_event", "surrogate"]
    split: Literal["discovery", "selection", "validation", "replay"]
    arm_id: Literal["control", "treatment"]
    replicate_index: int = Field(ge=0, le=99)
    seed: int = Field(ge=0, le=2_147_483_647)
    target_metric: str = Field(min_length=1, max_length=128)
    status: Literal["succeeded"] = "succeeded"
    metrics: dict[str, MetricObservation] = Field(min_length=1, max_length=100)
    evidence_label: str = Field(min_length=1, max_length=256)
    finished_at_utc: datetime

    @model_validator(mode="after")
    def validate_timestamp(self) -> RunResultArtifact:
        if self.finished_at_utc.tzinfo is None or self.finished_at_utc.utcoffset() is None:
            raise ValueError("finished_at_utc must be timezone-aware")
        return self


