"""Deterministic, provenance-gated evidence analysis for RESILIANT-Z Session 10.

This module only analyzes completed local result artifacts. It never starts an
executor, simulator, network request, or cloud job. The primary inferential
split is the predeclared validation split; discovery/selection/replay evidence
is retained in the audit trail but excluded from the primary decision.
"""

